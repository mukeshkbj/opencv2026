"""Agent traces from the bundled sample check, driven through the real API.

Run from server/:  python -m eval.trace
Writes docs/eval/agent-trace.json and docs/eval/agent-trace.md. The car spot runs twice: once with the real
side-step photo, and once with the camera held still for the side-step photo. Only the visual evidence differs.
"""
import json
import os
import tempfile
from pathlib import Path

os.environ.setdefault("TWICE_DATA", tempfile.mkdtemp())

from fastapi.testclient import TestClient  # noqa: E402

from twice.app import app, load, save  # noqa: E402

OUT = Path(__file__).resolve().parents[2] / "docs" / "eval"
client = TestClient(app)


def run(still_camera: bool = False) -> list[dict]:
    check = client.post("/api/samples/apartment").json()
    cid = check["id"]
    if still_camera:
        record = load(cid)
        for spot in record["spots"]:
            spot["sample"]["parallax"] = spot["sample"]["after"]
        save(record)
    spots = []
    for spot in check["spots"]:
        url = f"/api/checks/{cid}/spots/{spot['id']}/sample-shot"
        shots = 0
        state = None
        while shots < 4 and (state is None or state["status"] == "needs_followup"):
            state = client.post(url).json()["state"]
            shots += 1
        spots.append({"label": spot["label"], "photos": shots, "status": state["status"],
                      "findings": [{k: f[k] for k in ("id", "verdict", "kind", "evidence")} for f in state["findings"]],
                      "trace": [{k: t[k] for k in ("tool", "result", "decision")} for t in state["trace"]]})
    return spots


def markdown(runs: dict) -> str:
    lines = ["# Agent traces from the sample check", "",
             "Generated by `cd server && python -m eval.trace`, through the real API. Each row is one tool call. "
             "**Decision** is what the agent did next because of that result.", ""]
    for title, spots in runs.items():
        lines += [f"## {title}", ""]
        for s in spots:
            verdicts = ", ".join(f"{f['id']} {f['verdict']} ({f['kind']})" for f in s["findings"]) or "none"
            lines += [f"### {s['label']}", "", f"{s['photos']} photo(s) taken. Final findings: {verdicts}.", "",
                      "| # | Tool | OpenCV result | Decision |", "|---|---|---|---|"]
            lines += [f"| {i} | `{t['tool']}` | {t['result']} | {t['decision']} |" for i, t in enumerate(s["trace"], 1)]
            lines.append("")
    return "\n".join(lines)


def main() -> None:
    runs = {"Sample check": run(),
            "Counterfactual: the camera does not move for the side-step photo": run(still_camera=True)[:1]}
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "agent-trace.json").write_text(json.dumps(runs, indent=1))
    (OUT / "agent-trace.md").write_text(markdown(runs))
    print(markdown(runs))


if __name__ == "__main__":
    main()
